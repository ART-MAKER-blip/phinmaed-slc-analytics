import { ApiError, handleApi } from '@/lib/api';
import { writeAudit } from '@/lib/audit';
import { getPool } from '@/lib/db';
import { toCsv } from '@/lib/imports/csv';
import { loadProgramReport, resolveSelection } from '@/lib/results/server';
import { zoneRates } from '@/lib/results/types';
import { ZONES, ZONE_LABEL } from '@/lib/zones';

/**
 * Exports the report shown on /reports as CSV. The data is loaded again with the user's
 * scope, so an export never contains more than the user may see (test case 19). Each export
 * is recorded as a report run with its filters.
 */
export async function POST(request: Request) {
  return handleApi('report.generate', async (user) => {
    let form: FormData;
    try {
      form = await request.formData();
    } catch {
      throw new ApiError('Invalid request.');
    }
    const field = (name: string) => {
      const value = form.get(name);
      return typeof value === 'string' && value !== '' ? value : undefined;
    };
    const type = field('type') === 'semester' ? 'semester' : 'periodic';
    const selection = await resolveSelection(user, { campus: field('campus'), term: field('term'), period: field('period') });
    const program = field('program') ?? 'all';
    if (program !== 'all' && selection.programs !== 'all' && !selection.programs.includes(program)) {
      throw new ApiError('You cannot export results for that program.', 403);
    }
    const report = await loadProgramReport(user, selection, { type, program });
    if (!report.run) throw new ApiError('There are no results to export for this selection.', 404);

    const client = await getPool().connect();
    let reportId: number;
    try {
      await client.query('BEGIN');
      const inserted = await client.query<{ report_id: number }>(
        `INSERT INTO report_run (report_type, term_id, run_id, generated_by)
         SELECT $1, term_id, $2, $3 FROM snapshot_run WHERE run_id = $2 RETURNING report_id`,
        [type, report.run.runId, user.id],
      );
      reportId = inserted.rows[0].report_id;
      const filters = { campus: report.run.campus, term: report.run.term, period: report.run.period, program };
      await client.query(
        `INSERT INTO report_run_filter (report_id, filter_name, filter_value) SELECT $1, * FROM unnest($2::text[], $3::text[])`,
        [reportId, Object.keys(filters), Object.values(filters)],
      );
      await writeAudit({ userId: user.id, action: 'report_export', tableName: 'report_run', recordId: reportId, metadata: { type, ...filters } }, client);
      await client.query('COMMIT');
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }

    const zoneHeaders = ZONES.flatMap((z) => [`${ZONE_LABEL[z]} count`, `${ZONE_LABEL[z]} %`]);
    const countsRow = (counts: Record<string, number>, total: number) => {
      const rates = zoneRates({ green: counts.green, yellow: counts.yellow, red: counts.red }, total);
      return ZONES.flatMap((z) => [counts[z], rates[z]]);
    };
    const rows: (string | number | null)[][] = [
      ['Report', type === 'semester' ? 'Semester report' : 'Periodic report'],
      ['Report id', reportId],
      ['Campus', report.run.campusName],
      ['Term', report.run.term],
      ['Period', report.run.period],
      ['Programs', program === 'all' ? (selection.programs === 'all' ? 'All programs' : selection.programs.join(' ')) : program],
      ['Zone rule set', report.run.ruleSet],
      ['Snapshot run', report.run.runId],
      ['Generated by', user.name],
      ['Generated at', new Date().toISOString()],
      [],
      ['Student zones by program'],
      ['Program', 'Students', ...zoneHeaders],
      ...report.programs.map((p) => [p.program, p.total, ...countsRow(p.counts, p.total)]),
      [],
      ['Subject sections', 'Total', ...zoneHeaders],
      ['All shown', report.subjects.total, ...countsRow(report.subjects.counts, report.subjects.total)],
    ];
    if (report.outcome) {
      const o = report.outcome;
      rows.push([], ['Outcome review since', o.previousPeriod],
        ['Flagged before', 'Now green', 'Red to yellow', 'Unchanged', 'Moved to red', 'No current result'],
        [o.flaggedBefore, o.nowGreen, o.improved, o.unchanged, o.worse, o.noCurrentResult]);
    }
    if (report.campuses) {
      rows.push([], ['Campus comparison'], ['Campus', 'Period', 'Students', ...zoneHeaders],
        ...report.campuses.map((c) => [c.name, c.period ?? 'Not calculated', c.total, ...countsRow(c.counts, c.total)]));
    }

    const name = `slc-${type}-report-${report.run.campus}-${report.run.term}-${report.run.period}-${reportId}.csv`;
    return new Response(`﻿${toCsv(rows)}`, {
      headers: {
        'Content-Type': 'text/csv; charset=utf-8',
        'Content-Disposition': `attachment; filename="${name.replace(/[^\w.-]+/g, '_')}"`,
        'Cache-Control': 'private, no-store',
      },
    });
  });
}
